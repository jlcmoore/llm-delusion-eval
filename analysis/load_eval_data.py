def _read_log_manifest(log_path: Path) -> dict:
    """Read ``_journal/start.json`` from an eval log zip.

    Parameters
    ----------
    log_path:
        Path to a ``.eval`` file.

    Returns
    -------
    dict
        Parsed start manifest.
    """
    with zipfile.ZipFile(log_path, "r") as zf:
        return json.loads(zf.read("_journal/start.json"))


def _iter_samples(log_path: Path):
    """Yield parsed sample dicts from an eval log zip.

    Parameters
    ----------
    log_path:
        Path to a ``.eval`` file.

    Yields
    ------
    dict
        Parsed sample JSON.
    """
    with zipfile.ZipFile(log_path, "r") as zf:
        for name in sorted(zf.namelist()):
            if not name.startswith("samples/"):
                continue
            try:
                yield json.loads(zf.read(name))
            except EOFError:
                logger.warning(
                    "Truncated entry %s in %s; skipping", name, log_path.name
                )
                continue


def _select_latest_logs(logs_dir: Path) -> list[Path]:
    """Identify the latest log file per (model, reasoning_effort) config.

    When multiple log files exist for the same model configuration, keeps the
    one with the most completed samples (= most sample files inside the zip).

    Parameters
    ----------
    logs_dir:
        Directory containing ``.eval`` files.

    Returns
    -------
    list[Path]
        Deduplicated list of eval log paths (one per model config).
    """
    candidates: dict[str, list[tuple[int, Path]]] = defaultdict(list)

    for log_path in sorted(logs_dir.glob("*.eval")):
        try:
            manifest = _read_log_manifest(log_path)
        except (zipfile.BadZipFile, KeyError, json.JSONDecodeError) as exc:
            logger.warning("Skipping unreadable log %s: %s", log_path.name, exc)
            continue

        eval_info = manifest.get("eval", {})
        model = eval_info.get("model", "unknown")
        reasoning = eval_info.get("model_generate_config", {}).get("reasoning_effort")
        config_key = f"{model}|{reasoning}"

        # Count sample files without fully parsing them.
        with zipfile.ZipFile(log_path, "r") as zf:
            n_samples = sum(1 for name in zf.namelist() if name.startswith("samples/"))

        candidates[config_key].append((n_samples, log_path))

    selected = []
    for config_key, entries in candidates.items():
        best = max(entries, key=lambda pair: pair[0])
        selected.append(best[1])
        logger.info(
            "Selected %s (%d samples) for config %s",
            best[1].name,
            best[0],
            config_key,
        )

    return selected


def _parse_log_samples(
    log_path: Path,
    cutoffs: dict[str, int],
    metadata_map: dict,
) -> list[dict]:
    """Parse all samples from a single eval log file.

    Parameters
    ----------
    log_path:
        Path to a ``.eval`` file.
    cutoffs:
        Binarization cutoff mapping (annotation_id -> threshold).
    metadata_map:
        Annotation metadata mapping (normalized ID -> metadata object).

    Returns
    -------
    list[dict]
        Row dicts ready for DataFrame construction.
    """
    manifest = _read_log_manifest(log_path)
    eval_info = manifest.get("eval", {})
    model = eval_info.get("model", "unknown")
    reasoning = eval_info.get("model_generate_config", {}).get("reasoning_effort")

    label = _model_label(model, reasoning)

    rows = []
    for sample in _iter_samples(log_path):
        sample_id = sample.get("id", "")
        meta = sample.get("metadata", {}) or {}

        # Annotation ID
        annotations = meta.get("harmful_annotations", [])
        if annotations:
            annotation_id = normalize_id(annotations[0])
        else:
            annotation_id = "unknown"

        code_short = _shorten_code(annotation_id)
        category = CODE_CATEGORIES.get(
            code_short,
            getattr(metadata_map.get(annotation_id), "category", "unknown"),
        )

        # Window and turn info
        window_id = meta.get("window_id", "unknown")
        turn_index = meta.get("turn_index")

        # Score extraction
        scores_dict = sample.get("scores", {})
        score_obj = scores_dict.get("metadata_annotation_scorer", {})
        binary_score = score_obj.get("value")
        raw_score = None

        if score_obj.get("explanation"):
            try:
                expl = json.loads(score_obj["explanation"])
                raw_score = expl.get("raw_score")
            except (json.JSONDecodeError, TypeError):
                pass

        # Skip NaN scores
        if binary_score is not None:
            try:
                binary_score = float(binary_score)
                if math.isnan(binary_score):
                    binary_score = None
            except (ValueError, TypeError):
                binary_score = None

        if raw_score is not None:
            try:
                raw_score = float(raw_score)
                if math.isnan(raw_score):
                    raw_score = None
            except (ValueError, TypeError):
                raw_score = None

        rows.append(
            {
                "model": model,
                "reasoning_effort": reasoning,
                "model_label": label,
                "annotation_id": annotation_id,
                "code_short": code_short,
                "category": category,
                "window_id": window_id,
                "turn_index": turn_index,
                "score": binary_score,
                "raw_score": raw_score,
                "sample_id": sample_id,
            }
        )

    return rows


