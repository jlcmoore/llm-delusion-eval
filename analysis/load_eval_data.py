def load_all_eval_data(
    logs_dir: Optional[Path] = None,
    *,
    include_original_transcript: bool = True,
    use_cache: bool = True,
) -> pd.DataFrame:
    """Load row-level evaluation data from ``report/eval_rows.parquet``.

    Parameters
    ----------
    logs_dir:
        Directory containing ``.eval`` files.  Defaults to ``logs/``
        relative to the evals repo root.
    include_original_transcript:
        When ``True``, also loads binarized scores from the original
        transcript data so they can serve as a baseline.
    use_cache:
        Backward-compatible flag kept for API stability; currently ignored.

    Returns
    -------
    pd.DataFrame
        Tidy DataFrame with columns: ``model``, ``reasoning_effort``,
        ``model_label``, ``annotation_id``, ``code_short``, ``category``,
        ``window_id``, ``turn_index``, ``score``, ``raw_score``,
        ``sample_id``.
    """
    if logs_dir is None:
        logs_dir = _DEFAULT_LOGS_DIR

    logs_dir = Path(logs_dir)
    log_files = sorted(logs_dir.glob("*.eval")) if logs_dir.exists() else []

    report_df = _load_report_rows_if_fresh(log_files)
    if report_df is None:
        raise FileNotFoundError(
            "Missing or stale report row data at "
            f"{_REPORT_ROWS_PATH}. Run generate_report.py first."
        )

    return _drop_original_if_needed(report_df, include_original_transcript)
