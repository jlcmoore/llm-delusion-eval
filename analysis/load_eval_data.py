def _load_original_transcript_scores(
    cutoffs: dict[str, int],
    metadata_map: dict,
) -> pd.DataFrame:
    """Load binarized scores from the original transcript data.

    Reads the windows parquet and computes a binary score for each
    (window, turn, annotation) triple using the same cutoffs as the
    evaluation pipeline.

    Parameters
    ----------
    cutoffs:
        Binarization cutoff mapping.
    metadata_map:
        Annotation metadata mapping.

    Returns
    -------
    pd.DataFrame
        DataFrame in the same schema as the eval data, with
        ``model="original_transcript"``.
    """
    windows_path = resolve_path(
        "LLM_DELUSIONS_WINDOWS_PATH",
        DEFAULT_WINDOWS_PATH,
        require_local=True,
    )
    if not Path(windows_path).exists():
        logger.warning("Windows parquet not found at %s", windows_path)
        return pd.DataFrame()

    df_windows = pd.read_parquet(windows_path)
    rows = []

    for row_tuple in df_windows.itertuples():
        # The parquet schema uses ``eval_subset_id`` as the window
        # identifier and ``label`` as the annotation code.
        window_id = str(getattr(row_tuple, "eval_subset_id", ""))
        ann_id = normalize_id(str(getattr(row_tuple, "label", "")))
        messages = list(row_tuple.messages)

        if not ann_id or not window_id:
            continue

        source_id = get_source_id(ann_id)
        code_short = _shorten_code(ann_id)
        category = CODE_CATEGORIES.get(
            code_short,
            getattr(metadata_map.get(ann_id), "category", "unknown"),
        )
        cutoff = cutoffs.get(source_id, 7)

        for msg_idx, msg in enumerate(messages):
            msg_dict = (
                dict(msg)
                if hasattr(msg, "keys")
                else {k: getattr(msg, k) for k in msg._fields}
            )
            if msg_dict.get("role") != "assistant":
                continue

            raw_val = msg_dict.get(source_id)
            if raw_val is None or (isinstance(raw_val, float) and math.isnan(raw_val)):
                continue

            raw_score = float(raw_val)
            binary_score = 1.0 if raw_score >= cutoff else 0.0

            # Derive turn_index: count user messages before this one.
            turn_index = (
                sum(
                    1
                    for prior in messages[:msg_idx]
                    if (
                        dict(prior)
                        if hasattr(prior, "keys")
                        else {k: getattr(prior, k) for k in prior._fields}
                    ).get("role")
                    == "user"
                )
                - 1
            )
            turn_index = max(turn_index, 0)

            rows.append(
                {
                    "model": "original_transcript",
                    "reasoning_effort": None,
                    "model_label": "Original transcript",
                    "annotation_id": ann_id,
                    "code_short": code_short,
                    "category": category,
                    "window_id": window_id,
                    "turn_index": turn_index,
                    "score": binary_score,
                    "raw_score": raw_score,
                    "sample_id": f"orig.{window_id}.{msg_idx}",
                }
            )

    return pd.DataFrame(rows)


