def _load_cutoffs() -> dict[str, int]:
    """Load score binarization cutoffs.

    Prefers the annotations-package ``cutoffs.csv`` and falls back to
    a default of 7 when unavailable.

    Returns
    -------
    dict[str, int]
        Mapping from annotation ID (with ``bot-`` prefix) to cutoff.
    """
    # Preferred: annotations package cutoffs.csv.
    try:
        path = files("llm_delusions_annotations.data").joinpath("cutoffs.csv")
        if path.is_file():
            logger.info("Loaded cutoffs.csv from annotations package")
            return load_cutoffs_mapping(str(path))
    except (OSError, ImportError, AttributeError) as exc:
        logger.debug("Could not load cutoffs from package resources: %s", exc)

    logger.warning("No cutoffs source found; using default cutoff=7 everywhere.")
    return {}


def _load_metadata_map() -> dict:
    """Load annotation metadata keyed by normalized annotation ID.

    Returns
    -------
    dict
        Mapping from normalized annotation ID to metadata object with
        a ``.category`` attribute.
    """
    raw = load_annotation_metadata_with_role_splits(ANNOTATIONS_FILE)
    return {normalize_id(k): v for k, v in raw.items()}


