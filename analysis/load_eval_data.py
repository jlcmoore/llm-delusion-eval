"""Shared row-level data loading for evaluation analysis.

Loads ``report/eval_rows.parquet`` generated by ``generate_report.py`` and
returns a tidy DataFrame with binarized scores ready for analysis.

Usage::

    from analysis.load_eval_data import load_all_eval_data
    df = load_all_eval_data()
"""

